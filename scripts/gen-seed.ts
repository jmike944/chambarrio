// Generates supabase/seed.sql from the demo mock data (src/lib/data/jobs.ts), so a staging project
// can show the same Saltillo companies, branches and vacancies as demo mode.
// Run: node scripts/gen-seed.ts > supabase/seed.sql   (Node 22.18+/24 strips the TypeScript types)
import { COMPANIES, JOBS } from "../src/lib/data/jobs.ts";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const point = (lat: number, lng: number) => `extensions.st_point(${lng}, ${lat}, 4326)::extensions.geography`;

const companies = COMPANIES.map(
  (c) => `(${q(c.id)}, ${q(c.name)}, ${q(c.kind)}, ${q(c.size)}, ${c.verified}, ${q(c.about)}, ${q(c.employees)})`,
);
const branches = COMPANIES.flatMap((c) =>
  c.locations.map((b, i) => `(${q(b.id)}, ${q(c.id)}, ${q(b.name)}, ${q(b.colonia)}, ${point(b.location.lat, b.location.lng)}, ${i})`),
);
const jobs = JOBS.map(
  (j) =>
    `(${q(j.id)}, ${q(j.companyId)}, ${q(j.branchId)}, ${q(j.title)}, ${q(j.category)}, ${j.pay}, ${j.payMax ?? "null"}, ${q(j.period)}, ${q(j.shift)}, ${q(j.schedule)}, ${q(j.type)}, ${q(j.experience)}, ${arr(j.benefits)}, ${arr(j.requirements)}, ${q(j.description)}, ${j.openings}, ${j.urgent ?? false}, ${q(j.phone)}, now() - interval '${j.postedMinutesAgo} minutes')`,
);

console.log(
  [
    "-- Generated by scripts/gen-seed.ts from src/lib/data/jobs.ts. Demo data for staging; do not run in production.",
    "begin;",
    `insert into public.companies (id, name, kind, size, verified, about, employees) values\n${companies.join(",\n")}\non conflict (id) do nothing;`,
    `insert into public.branches (id, company_id, name, colonia, location, sort) values\n${branches.join(",\n")}\non conflict (id) do nothing;`,
    `insert into public.jobs (id, company_id, branch_id, title, category, pay, pay_max, period, shift, schedule, type, experience, benefits, requirements, description, openings, urgent, phone, created_at) values\n${jobs.join(",\n")}\non conflict (id) do nothing;`,
    "commit;",
  ].join("\n"),
);
